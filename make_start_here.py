def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="change nothing; exit 1 naming each file that differs")
    a = p.parse_args(argv)
    stale = []
    for key in OS:
        f = HERE / f"START_HERE_{key}.md"
        text = render(key)
        if a.check:
            if not f.is_file() or f.read_text(encoding="utf-8") != text:
                stale.append(f.name)
        else:
            f.write_text(text, encoding="utf-8", newline="\n")
            print(f"written {f.name}")
    if stale:
        print("stale (run python make_start_here.py): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
