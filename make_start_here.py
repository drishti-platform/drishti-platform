    cd_drishti = f'cd "{drishti}"'
    lock = ".." + o["sep"] + o["sep"].join(["config", "compute", "locks", "python.lock"])
    cd_console = 'cd "' + drishti + o["sep"] + 'drishti-console"'
    cd_plat = f'cd "{plat}"'
    other = [k for k in OS if k != key]
    others = " and ".join(f"`START_HERE_{k}.md`" for k in other)
